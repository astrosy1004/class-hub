// 공식: Jean Meeus, Astronomical Algorithms 25장 고정밀 방법(VSOP87 축약 계수 + 장동 · 광행차),
//       ΔT는 Espenak·Meeus 다항식. 1900~2100년 절입 시각 오차 약 1분 이내.
// 시각은 모두 율리우스일(JD, 세계시 UT 기준)로 주고받는다.

import { SOLAR_TERMS } from "./saju-data.js";

const RAD = Math.PI / 180;
const DAY_MS = 86400000;

export function jdFromMs(ms) {
  return ms / DAY_MS + 2440587.5;
}

export function msFromJd(jd) {
  return (jd - 2440587.5) * DAY_MS;
}

function normalizeDeg(deg) {
  return ((deg % 360) + 360) % 360;
}

// 세계시와 역학시의 차이(초). 1860~2150년 범위.
export function deltaT(year) {
  if (year < 1900) {
    const t = year - 1860;
    return 7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3 - 0.0004473624 * t ** 4 + t ** 5 / 233174;
  }
  if (year < 1920) {
    const t = year - 1900;
    return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4;
  }
  if (year < 1941) {
    const t = year - 1920;
    return 21.2 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3;
  }
  if (year < 1961) {
    const t = year - 1950;
    return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547;
  }
  if (year < 1986) {
    const t = year - 1975;
    return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718;
  }
  if (year < 2005) {
    const t = year - 2000;
    return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5;
  }
  if (year < 2050) {
    const t = year - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t ** 2;
  }
  return -20 + 32 * ((year - 1820) / 100) ** 2 - 0.5628 * (2150 - year);
}

